// Renders the order-confirmation email for every sample order in
// lib/order-confirmation-fixtures.ts, so the full design can be reviewed
// without placing an order or sending anything.
//
//   npm run email:preview
//
// Writes outputs/email-preview/ (git-ignored):
//   index.html          — all scenarios listed, each in a 640px-wide frame
//   <scenario>.html     — the exact HTML body Resend would send
//   <scenario>.txt      — the plain-text alternative
//
// Images point at the production site (or NEXT_PUBLIC_SITE_URL when it is an
// https origin), which is what a real inbox loads, so the preview needs network
// access to show photography. All copy and order data render offline.
import { mkdir, writeFile } from "node:fs/promises";
import { renderOrderConfirmationEmail } from "../lib/order-confirmation-email.ts";
import { orderEmailFixtures } from "../lib/order-confirmation-fixtures.ts";

const OUT = new URL("../outputs/email-preview/", import.meta.url);
await mkdir(OUT, { recursive: true });

const escape = s => String(s).replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");
const cards = [];

for (const fixture of orderEmailFixtures) {
  const { subject, html, text } = renderOrderConfirmationEmail(fixture.order);
  await writeFile(new URL(`${fixture.key}.html`, OUT), html);
  await writeFile(new URL(`${fixture.key}.txt`, OUT), text);
  cards.push(`
    <section>
      <h2>${escape(fixture.label)}</h2>
      <p class="meta"><code>${escape(fixture.key)}</code> — covers: ${escape(fixture.covers.join(", "))}</p>
      <p class="meta">Subject: <strong>${escape(subject)}</strong></p>
      <p class="meta"><a href="./${escape(fixture.key)}.html" target="_blank">open HTML</a> · <a href="./${escape(fixture.key)}.txt" target="_blank">plain text</a></p>
      <iframe src="./${escape(fixture.key)}.html" title="${escape(fixture.label)}"></iframe>
    </section>`);
  console.log(`${fixture.key.padEnd(18)} ${(html.length / 1024).toFixed(1)} KB HTML  ${(text.length / 1024).toFixed(1)} KB text  ${subject}`);
}

await writeFile(
  new URL("index.html", OUT),
  `<!DOCTYPE html><html lang="en"><head><meta charset="utf-8"><title>Wynn Essentials — order confirmation preview</title>
<style>
  body{margin:0;padding:32px;background:#f7f4ee;font:14px/1.5 Arial,Helvetica,sans-serif;color:#111}
  h1{font-family:Georgia,serif;font-weight:400;font-size:32px;margin:0 0 6px}
  section{margin:36px 0}
  h2{font-family:Georgia,serif;font-weight:400;font-size:22px;margin:0 0 4px}
  .meta{margin:2px 0;color:#5c564d;font-size:12px}
  iframe{margin-top:12px;width:640px;max-width:100%;height:1600px;border:1px solid #ded8ce;background:#fff}
</style></head><body>
<h1>Order confirmation — preview</h1>
<p class="meta">Sample data only. Generated by <code>npm run email:preview</code>.</p>
${cards.join("")}
</body></html>`,
);

console.log(`\nPreview written to ${new URL("index.html", OUT).pathname}`);

// Optional test send. Sample data only — this can never reach a customer:
//
//   npm run email:preview -- --send you@example.com [--fixture multiple-products]
//
// Needs RESEND_API_KEY in the environment. NOTIFY_FROM controls the From
// address; while it is unset the message goes out as onboarding@resend.dev,
// which Resend only delivers to the address that owns the API key.
const flag = name => {
  const at = process.argv.indexOf(`--${name}`);
  return at === -1 ? null : process.argv[at + 1] ?? null;
};
const to = flag("send");
if (to) {
  const apiKey = process.env.RESEND_API_KEY || process.env.wynnessentials_site;
  if (!apiKey) {
    console.error("Cannot send: set RESEND_API_KEY first.");
    process.exit(1);
  }
  const chosen = orderEmailFixtures.find(f => f.key === (flag("fixture") || "multiple-products"));
  if (!chosen) {
    console.error(`Unknown fixture. Available: ${orderEmailFixtures.map(f => f.key).join(", ")}`);
    process.exit(1);
  }
  const { subject, html, text } = renderOrderConfirmationEmail(chosen.order);
  const response = await fetch("https://api.resend.com/emails", {
    method: "POST",
    headers: { Authorization: `Bearer ${apiKey}`, "Content-Type": "application/json" },
    body: JSON.stringify({
      from: process.env.NOTIFY_FROM || "Wynn Essentials <onboarding@resend.dev>",
      to,
      // Marked in the subject so a test send is never mistaken for a real receipt.
      subject: `[TEST] ${subject}`,
      html,
      text,
    }),
  });
  console.log(response.ok ? `Test send OK — "${chosen.label}" to ${to}` : `Test send failed (${response.status}): ${await response.text()}`);
  if (!response.ok) process.exit(1);
}
